/// Assert that the `*_meta` constant generated by `bindgen.zig` (via `adapter/abi.zig`)
/// matches `canon.classifyZigFn` on the generated `*_Fn` type.
fn expectGeneratedMetaMatchesCanon(comptime FnT: type, comptime meta: anytype) !void {
    const lower_cls = comptime canon.classifyZigFn(FnT, .{
        .arch = .wasm32,
        .is_async = meta.is_async,
        .direction = .lower,
        .string_encoding_utf8 = meta.string_encoding_utf8,
    });
    try testing.expectEqual(meta.params_flat, @min(lower_cls.params_flat, 32));
    try testing.expectEqual(meta.results_flat, @min(lower_cls.results_flat, 32));
    try testing.expectEqual(meta.has_result, lower_cls.has_result);
    try testing.expectEqual(meta.needs_memory, lower_cls.needs_memory);
    try testing.expectEqual(meta.needs_realloc, lower_cls.lower_needs_realloc);
    try testing.expectEqual(meta.string_encoding_utf8, lower_cls.contains_string);
    if (@hasField(@TypeOf(meta), "lift_needs_post_return")) {
        const lift_cls = comptime canon.classifyZigFn(FnT, .{
            .arch = .wasm32,
            .is_async = meta.is_async,
            .direction = .lift,
            .string_encoding_utf8 = meta.string_encoding_utf8,
        });
        try testing.expectEqual(meta.lift_needs_memory, lift_cls.needs_memory);
        try testing.expectEqual(meta.lift_needs_realloc, lift_cls.lift_needs_realloc);
        try testing.expectEqual(meta.lift_needs_post_return, lift_cls.needs_post_return);
    }
}

